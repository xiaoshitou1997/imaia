/**
 * 后端错误码 → 前端文案映射。
 *
 * 后端 `Result.code` 是契约：前端按 code 给出稳定描述，不依赖后端 message 的措辞
 * （message 会随文案调整变化，code 不会）。未收录的 code 走统一兜底并记录原始码，
 * 便于排查而不是静默吞掉。
 *
 * 码段与后端 `ErrorCode` 枚举一一对应：1xxx 参数、2xxx 资源、3xxx 认证、4xxx 外部、9xxx 服务端。
 */
export const ERROR_CODE_COPY: Record<number, string> = {
  1400: '请求参数不合法。',
  1401: '请求格式有误。',
  1402: '时间格式不正确。',
  1403: '部分字段未通过校验。',
  1404: '自指令别名过长。',
  1405: '该平台不支持这个操作。',
  1406: '定时设置冲突，请只填一种。',
  1407: '任务内容不能为空。',
  1408: '定时表达式无效。',
  1409: '当前状态不允许此操作。',
  2404: '要访问的内容不存在。',
  2409: '数据冲突，请刷新后重试。',
  3401: '用户名或密码错误。',
  3503: '登录未启用，请先在服务端配置管理员凭据。',
  4502: '上游服务暂时不可用。',
  9500: '服务内部错误，请稍后重试。',
}

/** 兜底文案：不暴露内部细节，但保留原始码方便排查。 */
export function copyForCode(code: number | null | undefined): string {
  if (code === null || code === undefined) return '操作失败，请稍后重试。'
  return ERROR_CODE_COPY[code] ?? `操作失败（错误码 ${code}），请稍后重试。`
}
