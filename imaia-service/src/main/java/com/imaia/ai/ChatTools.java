package com.imaia.ai;

import com.imaia.config.ModelRegistry;
import com.imaia.repository.AiMemoryRepository;
import com.imaia.repository.ScheduledTaskRepository;
import org.springframework.ai.tool.ToolCallback;
import org.springframework.stereotype.Component;

import java.util.ArrayList;
import java.util.List;

/**
 * The chat model's toolset for one turn, derived from the model directory and the
 * conversation: generate_image / generate_video exist while the directory declares
 * a matching model, web_search while a search provider is configured, and the
 * conversation-bound tools (remember_fact, schedule_reminder) are always present.
 * Tool side effects persist immediately; generated bytes land in the turn collector
 * and the reply handler delivers them after the model loop ends.
 */
@Component
public class ChatTools {

    private final ModelRegistry registry;
    private final ImageGenerationClient imageClient;
    private final VideoGenerationClient videoClient;
    private final WebSearchClient webSearch;
    private final ScheduledTaskRepository tasks;
    private final AiMemoryRepository memories;

    public ChatTools(ModelRegistry registry, ImageGenerationClient imageClient,
            VideoGenerationClient videoClient, WebSearchClient webSearch,
            ScheduledTaskRepository tasks, AiMemoryRepository memories) {
        this.registry = registry;
        this.imageClient = imageClient;
        this.videoClient = videoClient;
        this.webSearch = webSearch;
        this.tasks = tasks;
        this.memories = memories;
    }

    /** The tools for one turn, bound to the conversation that triggered it. */
    public List<ToolCallback> tools(long conversationId, List<GeneratedMedia> collector) {
        List<ToolCallback> tools = new ArrayList<>();
        if (registry.hasProtocol(ModelRegistry.PROTOCOL_IMAGES)) {
            tools.add(new ImageGenerationTool(imageClient, collector));
        }
        if (registry.hasProtocol(ModelRegistry.PROTOCOL_VIDEO)) {
            tools.add(new VideoGenerationTool(videoClient, collector));
        }
        if (webSearch.available()) {
            tools.add(new WebSearchTool(webSearch));
        }
        tools.add(new RememberFactTool(conversationId, memories));
        tools.add(new ScheduleReminderTool(conversationId, tasks));
        return tools;
    }
}
